#!/usr/bin/env python3
"""Generate docs/ATTACK-COVERAGE.md from the ATT&CK annotations in savedsearches.conf.

The annotations (``action.correlationsearch.annotations``) are the only
source; nothing in the document is typed by hand, so the matrix can never
drift from the detections.

    python scripts/attack_coverage.py            # rewrite docs/ATTACK-COVERAGE.md
    python scripts/attack_coverage.py --check    # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from harness import APP_DIR, REPO_ROOT  # noqa: E402
from harness.catalog import TECHNIQUE_TACTICS, Detection, load_catalog  # noqa: E402

TACTIC_ORDER = ["Initial Access", "Execution", "Persistence", "Privilege Escalation", "Defense Evasion",
                "Credential Access", "Discovery", "Lateral Movement", "Collection", "Command and Control",
                "Exfiltration", "Impact"]


def primary_tactics(technique: str) -> list[str]:
    """All tactics a technique belongs to (a technique may sit under several)."""
    return [t.strip() for t in TECHNIQUE_TACTICS.get(technique.split(".")[0], "Unknown").split("/")]


def render(detections: list[Detection]) -> str:
    by_technique: dict[str, list[Detection]] = defaultdict(list)
    for detection in detections:
        for technique in detection.mitre_attack:
            by_technique[technique].append(detection)
    by_tactic: dict[str, set[str]] = defaultdict(set)
    for technique in by_technique:
        for tactic in primary_tactics(technique):
            by_tactic[tactic].add(technique)
    parent_techniques = {t.split(".")[0] for t in by_technique}

    lines = [
        "# MITRE ATT&CK coverage",
        "",
        "Generated by `scripts/attack_coverage.py` from the `action.correlationsearch.annotations` field of every",
        "stanza in `TA-threat-detection/default/savedsearches.conf`. Do not edit by hand; run `make coverage`.",
        "",
        "## Summary",
        "",
        f"- Detections: **{len(detections)}**",
        f"- Techniques and sub-techniques referenced: **{len(by_technique)}** ({len(parent_techniques)} parent techniques)",
        f"- Tactics covered: **{len([t for t in TACTIC_ORDER if by_tactic.get(t)])}** of {len(TACTIC_ORDER)}",
        "",
        "| Tactic | Techniques | Detections |",
        "|---|---:|---:|",
    ]
    for tactic in TACTIC_ORDER:
        techniques = by_tactic.get(tactic, set())
        ids = {d.id for t in techniques for d in by_technique[t]}
        lines.append(f"| {tactic} | {len(techniques)} | {len(ids)} |")
    lines += ["", "## Matrix", ""]
    for tactic in TACTIC_ORDER:
        techniques = sorted(by_tactic.get(tactic, set()))
        lines.append(f"### {tactic}")
        lines.append("")
        if not techniques:
            lines.append("_No detections map to this tactic yet._")
            lines.append("")
            continue
        lines.append("| Technique | Name | Detections |")
        lines.append("|---|---|---|")
        for technique in techniques:
            dets = by_technique[technique]
            refs = ", ".join(f"[{d.id}](../detections/{d.slug}.md)" for d in sorted(dets, key=lambda d: d.id))
            name = dets[0].technique_name(technique)
            url = f"https://attack.mitre.org/techniques/{technique.replace('.', '/')}/"
            lines.append(f"| [{technique}]({url}) | {name} | {refs} |")
        lines.append("")
    lines += ["## Detections", "", "| ID | Detection | Severity | Techniques | NIST CSF | Data source |", "|---|---|---|---|---|---|"]
    for d in detections:
        techniques = ", ".join(d.mitre_attack)
        lines.append(f"| [{d.id}](../detections/{d.slug}.md) | {d.name} | {d.severity_name} | {techniques} | "
                     f"{', '.join(d.nist)} | {'; '.join(d.data_sources)} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the ATT&CK coverage document.")
    parser.add_argument("--out", default=str(REPO_ROOT / "docs" / "ATTACK-COVERAGE.md"))
    parser.add_argument("--app", default=str(APP_DIR))
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if the file is out of date")
    args = parser.parse_args(argv)
    text = render(load_catalog(Path(args.app)))
    out = Path(args.out)
    if args.check:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(f"{out} is out of date; run: python scripts/attack_coverage.py")
            return 1
        print(f"{out} is up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
